/** Writes `../vectors.json` into a Kotlin source file, as common test code can't read files on native targets. */
abstract class EmbedVectors : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val vectors: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val json = vectors.get().asFile.readText()
        val source =
            buildString {
                append("// Generated by the embedVectors task from ../vectors.json. Do not edit.\n")
                append("package dev.edde746.trave\n\n")
                append("internal val VECTORS_JSON: String = buildString {\n")
                for (line in json.lines()) {
                    append("    append(\"")
                    for (c in line) {
                        when {
                            c == '\\' -> append("\\\\")
                            c == '"' -> append("\\\"")
                            c == '$' -> append("\\$")
                            c < ' ' || c > '~' -> append("\\u").append(c.code.toString(16).padStart(4, '0'))
                            else -> append(c)
                        }
                    }
                    append("\\n\")\n")
                }
                append("}\n")
            }
        val dir = outputDir.get().asFile.resolve("dev/edde746/trave")
        dir.mkdirs()
        dir.resolve("Vectors.kt").writeText(source)
    }
}

val embedVectors =
    tasks.register<EmbedVectors>("embedVectors") {
